const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { Tutorial } = require("../app/tutorial.cjs");
const { Review } = require("../app/review.cjs");
const { git } = require("../app/repository.cjs");
const { createReview } = require("./review-fixture.cjs");

test("Practice teaches actual review decisions while preserving the selected workspace", async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-tutorial-"));
  t.after(() => fs.rm(temp, { recursive: true, force: true }));
  const realRoot = path.join(temp, "real");
  const plan = await createReview(realRoot);
  const profile = path.join(temp, "profile");
  const review = new Review(path.join(profile, "review.json"), realRoot);
  await review.choose(realRoot);
  await review.act("start");
  await review.act("draft", { key: "Teams message", text: "Keep my real draft." });
  await review.act("position", { hunk: 2, screen: { page: 2, offset: 36 } });
  const stateBefore = await fs.readFile(path.join(realRoot, ".review/state.json"), "utf8");
  const preferencesBefore = await fs.readFile(review.preferences, "utf8");
  let tutorial = new Tutorial(profile, review);
  await tutorial.load();
  let { view } = await tutorial.control("start");
  assert.equal(view.tutorial.step, 0);
  assert.equal(view.hunks.length, 4);
  assert.notEqual(view.root, realRoot);
  const originalSampleHeads = await Promise.all(Object.keys(view.patches).map(repo => git(path.join(view.root, repo), ["rev-parse", "master"])));
  await assert.rejects(tutorial.act("accept"), /waiting for step 1/);
  await tutorial.act("start");
  view = await tutorial.act("position", { screen: { page: 1 } });
  assert.equal(view.tutorial.step, 1);
  await tutorial.act("position", { hunk: 1, screen: { page: 1 } });
  assert.equal(tutorial.state.step, 1, "navigation alone does not mark a hunk read");
  await tutorial.act("previous");
  await tutorial.act("next");
  await tutorial.act("next");
  await tutorial.act("next");
  view = await tutorial.act("next");
  assert.equal(view.tutorial.step, 2);
  await tutorial.act("save-field", { key: "Teams message", text: "I wrote this before requesting changes." });
  await tutorial.act("draft", { key: "comment", text: "Zero is a real limit. Keep it." });
  assert.equal(tutorial.state.step, 2, "a note draft is not a saved observation");
  await tutorial.control("leave");
  tutorial = new Tutorial(profile, review);
  await tutorial.load();
  ({ view } = await tutorial.control("start"));
  assert.equal(view.tutorial.step, 2);
  assert.equal(view.drafts.comment, "Zero is a real limit. Keep it.");
  view = await tutorial.act("comment", { text: view.drafts.comment, onHunk: true });
  assert.equal(view.tutorial.step, 3);
  view = await tutorial.act("reject", { text: "Say which files changed and what you checked." });
  assert.equal(view.tutorial.step, 4);
  assert.equal(view.status, "changes_requested");
  view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 4, "an earlier message edit does not complete the current lesson");
  await assert.rejects(tutorial.act("resolve"), /waiting for step 5/);
  await tutorial.act("draft", { key: "Teams message", text: "Use Python logging and find files beside the code." });
  assert.equal(tutorial.state.step, 4);
  view = await tutorial.act("save-field", { key: "Teams message", text: "Use Python logging and find files beside the code." });
  assert.equal(view.tutorial.step, 5);
  view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 5, "reading does not mark the request fixed");
  view = await tutorial.act("resolve");
  assert.equal(view.tutorial.step, 6);
  tutorial.state.step = 5;
  await tutorial.save();
  tutorial = new Tutorial(profile, review);
  await tutorial.load();
  view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 6, "a saved resolution recovers without another Request fixed button");
  view = await tutorial.act("accept");
  assert.equal(view.tutorial.step, 7);
  assert.equal(view.round, null);
  // Git acceptance can finish before tutorial.json is saved.
  tutorial.state.step = 6;
  await tutorial.save();
  tutorial = new Tutorial(profile, review);
  await tutorial.load();
  view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 7, "accepted commits recover without asking for another acceptance");
  assert.match(view.master, /Use Python logging/);
  assert.match(view.board, /\[x\] \[R01\]/);
  for (const [i, repo] of ["sample-tools", "sample-files"].entries()) {
    const sample = path.join(view.root, repo);
    assert.notEqual(await git(sample, ["rev-parse", "master"]), originalSampleHeads[i]);
    assert.match(await git(sample, ["show", i === 0 ? "master:run.py" : "master:words.py"]), i === 0 ? /import logging/ : /__file__/);
  }
  view = await tutorial.act("position", { screen: { page: 5, record: "master" } });
  assert.equal(view.tutorial.step, 8);
  assert.equal(view.tutorial.completed, true);
  ({ view } = await tutorial.control("leave"));
  assert.equal(view.root, realRoot);
  assert.equal(view.drafts["Teams message"], "Keep my real draft.");
  assert.equal(view.hunk, 2);
  assert.equal(view.screen.offset, 36);
  assert.equal(await fs.readFile(path.join(realRoot, ".review/state.json"), "utf8"), stateBefore);
  assert.equal(await fs.readFile(review.preferences, "utf8"), preferencesBefore);
  for (const [repo, meta] of Object.entries(plan.repositories)) assert.equal(await git(path.join(realRoot, repo), ["rev-parse", "master"]), meta.base);
  tutorial = new Tutorial(profile, review);
  await tutorial.load();
  assert.equal(tutorial.status().completed, true);
  ({ view } = await tutorial.control("restart"));
  assert.equal(view.tutorial.step, 0);
  assert.equal(view.comments.length, 0);
  assert.equal(view.hunks.some(h => h.seen), false);
  assert.equal(view.round.teams, "Clean things up.");
  assert.equal(view.tutorial.completed, false);
  assert.equal(await fs.readFile(path.join(realRoot, ".review/state.json"), "utf8"), stateBefore);
});

test("Leaving an unfinished tutorial dismisses onboarding and preserves practice progress", async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-leave-practice-"));
  t.after(() => fs.rm(temp, { recursive: true, force: true }));
  const realRoot = path.join(temp, "real");
  await createReview(realRoot);
  let tutorial = new Tutorial(temp, new Review(path.join(temp, "review.json"), realRoot));
  await tutorial.control("start");
  await tutorial.act("start");
  await tutorial.act("position", { screen: { page: 1 } });
  const { view } = await tutorial.control("leave");
  assert.equal(view.root, realRoot);
  assert.equal(view.tutorial.dismissed, true);
  tutorial = new Tutorial(temp, tutorial.review);
  await tutorial.load();
  assert.equal(tutorial.status().dismissed, true);
  assert.equal((await tutorial.control("start")).view.tutorial.step, 1);
});

test("Recreating missing practice repositories saves the reset progress before the next launch", async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-missing-practice-"));
  t.after(() => fs.rm(temp, { recursive: true, force: true }));
  let tutorial = new Tutorial(temp, new Review(path.join(temp, "review.json"), path.join(temp, "real")));
  await tutorial.control("start");
  tutorial.state.step = 5;
  await tutorial.save();
  await fs.rm(tutorial.root, { recursive: true });
  tutorial = new Tutorial(temp, tutorial.review);
  await tutorial.load();
  assert.equal(tutorial.status().step, 0);
  tutorial = new Tutorial(temp, tutorial.review);
  await tutorial.load();
  assert.equal(tutorial.status().step, 0, "a second launch must not restore progress from the deleted repos");
});

test("Practice works without a prepared workspace; skipping and resuming survive restarts", async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-first-review-"));
  t.after(() => fs.rm(temp, { recursive: true, force: true }));
  const missing = path.join(temp, "not-prepared");
  const review = new Review(path.join(temp, "review.json"), missing);
  let tutorial = new Tutorial(path.join(temp, "profile"), review);
  const skipped = await tutorial.control("skip");
  assert.equal(skipped.view, null);
  tutorial = new Tutorial(path.join(temp, "profile"), review);
  await tutorial.load();
  assert.equal(tutorial.state.dismissed, true);
  await tutorial.control("start");
  await tutorial.act("start");
  await tutorial.act("position", { screen: { page: 1 } });
  tutorial = new Tutorial(path.join(temp, "profile"), review);
  await tutorial.load();
  assert.equal(tutorial.state.active, true);
  const view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 1);
  await assert.rejects(fs.access(missing));
  await assert.rejects(tutorial.control("arbitrary"), /Unknown practice action/);
});

test("The Python tutorial keeps old practice files and starts its own review", async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-python-practice-"));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const old = path.join(directory, "practice-review");
  await fs.mkdir(old);
  await fs.writeFile(path.join(old, "my-note.txt"), "Keep the old sample too.\n");
  await fs.writeFile(path.join(directory, "tutorial.json"), JSON.stringify({ active: true, step: 5, completed: true }));
  const tutorial = new Tutorial(directory, new Review(path.join(directory, "review.json"), path.join(directory, "real")));
  await tutorial.load();
  const view = await tutorial.act("read");
  assert.equal(view.tutorial.step, 0);
  assert.equal(view.tutorial.completed, false);
  assert.equal(await fs.readFile(path.join(old, "my-note.txt"), "utf8"), "Keep the old sample too.\n");
  assert.match(view.patches["sample-tools"], /logging\.basicConfig/);
  assert.match(view.patches["sample-files"], /__file__/);
  assert.match(view.patches["sample-files"], /limit \?\? 10/);
  assert.match(view.round.validation, /other dependency versions are untested/);
});
