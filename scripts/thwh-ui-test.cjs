const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { createReview } = require("../test/review-fixture.cjs");
const { git } = require("../src/repository.cjs");
(async () => {
  const root = path.resolve(__dirname, "..");
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "thwh-ui-"));
  const reviewRoot = path.join(temp, "review");
  const plan = await createReview(reviewRoot);
  await fs.mkdir(path.join(reviewRoot, "The Review"));
  await fs.rename(path.join(reviewRoot, "Kanbun.md"), path.join(reviewRoot, "The Review/The Board.md"));
  await fs.writeFile(path.join(reviewRoot, "The Review/The Task.md"), "# Task\nA real review task.");
  const env = { ...process.env, THWH_DATA_DIR: path.join(temp, "profile"), YHWH_REVIEW_ROOT: reviewRoot };
  delete env.ELECTRON_RUN_AS_NODE;
  const artifacts = path.join(root, "artifacts");
  await fs.mkdir(artifacts, { recursive: true });
  let app, page;
  const errors = [];
  const click = action => page.locator(`[data-action="${action}"]`).first().click();
  const view = () => page.evaluate(() => window.yhwh.reviewRead());
  const go = async n => { await page.locator(`nav [data-page="${n}"]`).click(); await page.waitForFunction(n => document.querySelector(".tw-page-name")?.textContent === ["Start", "Diff", "Messages", "Notes", "Roadmap", "Context"][n], n); };
  async function launch() {
    app = await electron.launch({ executablePath: require("./runtime.cjs")(), args: [root, "--thwh", "--disable-gpu"], env, timeout: 60000 });
    page = await app.firstWindow();
    page.on("pageerror", error => errors.push(error.message));
    await page.locator(".tw-app").waitFor();
  }
  try {
    await launch();
    await require("./help-menu-test.cjs")(app);
    assert.equal(await page.locator("body").getAttribute("data-theme"), "yhwh");
    assert.equal(await page.locator("input[type=radio]").count(), 0);
    assert.equal(await page.locator("#energy").getAttribute("step"), "50");
    await page.screenshot({ path: path.join(artifacts, "thwh-yhwh.png") });
    await click("advance"); // resume and Start -> Diff
    await page.locator(".tw-diff").waitFor();
    await click("advance");
    await page.waitForFunction(() => document.querySelector(".tw-diff-toolbar")?.textContent.includes("Hunk 2/4"));
    assert.equal((await view()).hunks[0].seen, true);
    await click("note");
    await page.locator("#review-note").fill("Keep this edge case. <img src=x onerror=alert(1)>");
    await page.waitForFunction(async () => (await window.yhwh.reviewRead()).drafts.comment?.includes("edge case"));
    await app.close(); app = null;
    await launch();
    assert.equal(await page.locator("#review-note").inputValue(), "Keep this edge case. <img src=x onerror=alert(1)>");
    await click("comment");
    await page.locator(".tw-notes article").waitFor();
    assert.equal((await view()).drafts.comment, undefined);
    assert.match((await view()).comments[0].anchor, /@@ -47/);
    assert.equal(await page.locator(".tw-notes img").count(), 0);
    await go(2);
    await page.locator('[data-editor="Teams message"]').fill("A revised, concrete handoff.");
    await page.locator('[data-editor="Teams message"]').press("Control+s");
    await page.waitForFunction(async () => (await window.yhwh.reviewRead()).round.teams === "A revised, concrete handoff.");
    const before = await page.locator(".tw-main").boundingBox();
    await page.waitForFunction(() => !document.querySelector("#energy").disabled);
    await page.locator("#energy").focus();
    await page.locator("#energy").press("ArrowLeft");
    await page.waitForFunction(() => document.body.dataset.theme === "nietzsche");
    await page.getByText("God is dead.", { exact: true }).waitFor();
    await require("./help-menu-test.cjs")(app);
    const after = await page.locator(".tw-main").boundingBox();
    assert.deepEqual(before, after);
    assert.equal(await page.locator(".tw-divine-orbit").count(), 0);
    await page.screenshot({ path: path.join(artifacts, "thwh-nietzsche.png") });
    // Switching to Dawkins stays in this window and retains unfinished work.
    await page.locator('[data-editor="Teams message"]').fill("Unfinished handoff for Dawkins.");
    await page.locator("#assistant-message").fill("An unsent question.");
    const savedPlace = await view();
    await page.locator("#energy").press("Home");
    await page.waitForFunction(() => document.body.dataset.theme === "dawkins" && !document.querySelector("#energy").disabled);
    assert.equal(await page.locator("#energy").getAttribute("aria-valuetext"), "dawkins, 0 percent");
    assert.equal(await page.locator(".tw-widget").count(), 0);
    assert.equal(await page.locator("#assistant-message").inputValue(), "An unsent question.");
    assert.equal(await page.locator('[data-editor="Teams message"]').inputValue(), "Unfinished handoff for Dawkins.");
    assert.equal((await view()).hunk, savedPlace.hunk);
    assert.equal((await view()).active, savedPlace.active);
    await app.close(); app = null;
    await launch();
    assert.equal(await page.locator("body").getAttribute("data-theme"), "dawkins");
    assert.equal(await page.locator('[data-editor="Teams message"]').inputValue(), "Unfinished handoff for Dawkins.");
    await page.locator('[data-editor="Teams message"]').fill("A revised, concrete handoff.");
    await page.locator('[data-editor="Teams message"]').press("Control+s");
    await page.waitForFunction(async () => !("Teams message" in (await window.yhwh.reviewRead()).drafts));
    await page.waitForFunction(() => !document.querySelector("#energy").disabled);
    assert.match(await page.locator('[data-editor="Teams message"]').evaluate(el => getComputedStyle(el).fontFamily), /Mono|monospace/);
    assert.equal(await page.locator("body").evaluate(el => getComputedStyle(el).backgroundColor), "rgb(0, 0, 0)");
    await page.screenshot({ path: path.join(artifacts, "thwh-dawkins.png") });
    await require("./help-menu-test.cjs")(app);
    await go(1);
    await page.screenshot({ path: path.join(artifacts, "thwh-dawkins-diff.png") });
    await click("settings");
    await page.locator('[name="mode"]').selectOption("offline");
    await page.locator("#settings-form button[type=submit]").click();
    await page.locator("#assistant-message").fill("What are we reviewing?");
    await page.locator("#assistant-form button[type=submit]").click();
    await page.locator(".tw-chat-log article.assistant").waitFor();
    assert.doesNotMatch(await page.locator(".tw-chat-log").textContent(), /Yahweh|Genesis|come down/i);
    await go(3);
    await page.locator("#review-note").fill("Please explain the evidence.");
    await click("reject");
    await page.waitForFunction(async () => (await window.yhwh.reviewRead()).status === "changes_requested");
    await click("accept");
    await page.waitForFunction(() => document.querySelector("#toast")?.textContent.includes("requested changes"));
    await click("resolve");
    await go(1);
    await click("edit-patch");
    const patch = (await view()).patches["alpha"];
    await page.locator('[data-editor="alpha patch"]').fill("Not a patch\n");
    await click("save-patch");
    await click("accept");
    await page.locator(".tw-modal").waitFor();
    await click("confirm-accept");
    await page.waitForFunction(() => document.querySelector("#toast")?.classList.contains("error"));
    for (const [name, meta] of Object.entries(plan.repositories)) assert.equal(await git(path.join(reviewRoot, name), ["rev-parse", "master"]), meta.base);
    await page.locator('[data-editor="alpha patch"]').fill(patch);
    await click("save-patch");
    await click("accept");
    await click("confirm-accept");
    await page.waitForFunction(async () => (await window.yhwh.reviewRead()).round?.id === "R02");
    assert.match((await view()).master, /revised, concrete handoff/);
    await go(5);
    await page.locator('[data-document="The Review/The Task.md"]').click();
    await page.getByText("A real review task.", { exact: false }).waitFor();
    await page.setViewportSize({ width: 1100, height: 740 });
    await page.screenshot({ path: path.join(artifacts, "thwh-dawkins-compact.png") });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await click("accept");
    await click("confirm-accept");
    await page.waitForFunction(async () => !(await window.yhwh.reviewRead()).round);
    await go(5);
    await page.locator('[data-document="board"]').click();
    await page.getByText("User task", { exact: false }).waitFor();
    assert.deepEqual(errors, []);
    assert.equal(JSON.parse(await fs.readFile(path.join(env.THWH_DATA_DIR, "thwh.json"), "utf8")).energy, 0);
    await page.locator("#energy").press("End");
    await page.waitForFunction(() => document.body.dataset.theme === "yhwh");
    await page.locator(".tw-divine-orbit").waitFor();
    console.log("✓ THWH: all three desktop themes, in-place switching, durable drafts, plain assistant, hunk markers, notes, rejection, paired acceptance and completion");
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(artifacts, "thwh-failure.png") }).catch(() => {});
    throw error;
  } finally {
    if (app) await app.close();
    await fs.rm(temp, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
