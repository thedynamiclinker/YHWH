#!/usr/bin/env node
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { root } = require('../lib/paths.cjs');

const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const dataHome = () => path.resolve(process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local/share'));
const read = file => fs.readFile(file).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
// Desktop Entry quoting has two escaping layers; % also introduces field codes.
const value = text => String(text).replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\r/g, '\\r');
const argument = text => '"' + value(String(text).replace(/[\\"`$]/g, '\\$&')).replace(/%/g, '%%') + '"';
const recordPath = mode => path.join(dataHome(), 'yhwh', `desktop-${mode}.json`);

async function installDesktop(mode, prefix, workspace) {
  if (!['install', 'develop'].includes(mode)) throw new Error('Use install or develop.');
  const development = mode === 'develop', id = development ? 'yhwh-development' : 'yhwh';
  const checkoutAssets = path.resolve(root, '../usr/share');
  const shared = require('node:fs').existsSync(checkoutAssets) ? checkoutAssets : path.join(root, 'etc/desktop');
  const packageRoot = path.join(prefix, 'lib/node_modules/yhwh-system');
  const launcher = path.join(dataHome(), 'yhwh', `${id}.cjs`);
  const icon = path.join(dataHome(), 'icons/hicolor/scalable/apps', `${id}.svg`);
  const desktop = path.join(dataHome(), 'applications', `${id}.desktop`);
  const runtime = require('../lib/electron.cjs')();
  const launchSource = `// Generated by YHWH; re-run make ${mode} to refresh.\nprocess.chdir(${JSON.stringify(path.resolve(workspace))});\nprocess.env.YHWH_ELECTRON = ${JSON.stringify(runtime)};\nprocess.env.YHWH_DESKTOP_FLAVOR = ${JSON.stringify(development ? 'development' : 'installed')};\ndelete process.env.YHWH_TAB;\ndelete process.env.ELECTRON_RUN_AS_NODE;\nrequire(${JSON.stringify(path.join(packageRoot, 'bin/default/cli.cjs'))}).main(process.argv[2] ? ['open', process.argv[2]] : ['--cwd', process.cwd()]).catch(error => { console.error(error); process.exitCode = 1; });\n`;
  const template = await fs.readFile(path.join(shared, 'applications', `${id}.desktop`), 'utf8');
  const entry = template.replace('@EXEC@', () => `${argument(process.execPath)} ${argument(launcher)} %f`)
    .replace('@NODE@', () => value(process.execPath)).replace('@ICON@', () => value(icon));
  const pending = new Map([[launcher, Buffer.from(launchSource)], [icon, await fs.readFile(path.join(shared, 'icons/hicolor/scalable/apps', `${id}.svg`))], [desktop, Buffer.from(entry)]]);
  const saved = await read(recordPath(mode));
  const previous = saved ? JSON.parse(saved) : { entries: {} };
  for (const filename of pending.keys()) {
    const bytes = await read(filename);
    if (bytes && digest(bytes) !== previous.entries[filename]) throw new Error('Desktop file contains unowned or modified data; preserved: ' + filename);
  }
  const entries = {};
  for (const [filename, bytes] of pending) {
    await fs.mkdir(path.dirname(filename), { recursive: true });
    await fs.writeFile(filename, bytes); entries[filename] = digest(bytes);
  }
  await fs.mkdir(path.dirname(recordPath(mode)), { recursive: true });
  await fs.writeFile(recordPath(mode), JSON.stringify({ entries }, null, 2) + '\n');
  spawnSync('update-desktop-database', [path.join(dataHome(), 'applications')], { stdio: 'ignore' });
  spawnSync('gtk-update-icon-cache', ['--force', '--ignore-theme-index', path.join(dataHome(), 'icons/hicolor')], { stdio: 'ignore' });
  console.log(`Desktop app: ${desktop}`);
}

async function uninstallDesktop() {
  for (const mode of ['install', 'develop']) {
    const saved = await read(recordPath(mode));
    if (!saved) continue;
    const { entries } = JSON.parse(saved), preserved = {};
    for (const [filename, expected] of Object.entries(entries)) {
      const bytes = await read(filename);
      if (!bytes) continue;
      if (digest(bytes) === expected) await fs.unlink(filename);
      else { preserved[filename] = expected; console.log('Preserved modified desktop file: ' + filename); }
    }
    if (Object.keys(preserved).length) await fs.writeFile(recordPath(mode), JSON.stringify({ entries: preserved }, null, 2) + '\n');
    else await fs.unlink(recordPath(mode));
  }
}
module.exports = { installDesktop, uninstallDesktop };
if (require.main === module) {
  const [mode, override, workspace = process.cwd()] = process.argv.slice(2);
  const prefix = path.resolve(override || path.join(os.homedir(), mode === 'develop' ? 'world' : 'world/mnt/sinai'));
  (mode === 'uninstall' ? uninstallDesktop() : installDesktop(mode, prefix, workspace)).catch(error => { console.error('yhwh desktop: ' + error.message); process.exitCode = 1; });
}
