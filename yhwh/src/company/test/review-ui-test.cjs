const { _electron: electron } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { execFile } = require("node:child_process");
const { promisify } = require("node:util");
const { createReview } = require("./review-fixture.cjs");
const { git } = require("../../../lib/company/repository.cjs");

(async () => {
  const root = path.join(__dirname, "..");
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "yhwh-review-ui-"));
  const reviewRoot = path.join(temp, "review workspace");
  const artifacts = require('../../../lib/paths.cjs').output('company', 'screenshots');
  await fs.mkdir(artifacts, { recursive: true });
  const plan = await createReview(reviewRoot);
  const env = { ...process.env, YHWH_DATA_DIR: path.join(temp, "data"), YHWH_REVIEW_ROOT: reviewRoot };
  delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = require("../../../lib/electron.cjs")();
  const errors = [];
  let app, page;
  async function launch() {
    app = await electron.launch({ executablePath, args: [process.env.YHWH_TEST_APP || root, "--disable-gpu"], env, timeout: 60000 });
    page = await app.firstWindow();
    page.on("pageerror", (error) => errors.push(error.message));
    await page.locator(".shell").waitFor();
    const fact = page.locator(".modal");
    if (await fact.count()) await page.locator('[data-action="close-dialog"]').last().click();
    await page.locator('.rail-bottom [data-action="settings"]').click();
    await page.locator('#settings-form [name="mode"]').selectOption("offline");
    await page.locator("#settings-form button:not([data-action])").click();
    await page.locator(".modal").waitFor({ state: "detached" });
    await page.locator('.sidebar [data-action="review"]').click();
    await page.locator(".code-session").waitFor();
  }
  const click = async (action) => page.locator(`[data-action="code-${action}"]`).click();
  const section = async (id) => page.locator(`[data-section="${id}"]`).click();
  const read = () => page.evaluate(() => window.yhwh.reviewRead());
  const cli = (...args) => promisify(execFile)("python3", [path.join(root, "../../bin/company/review"), "--root", reviewRoot, ...args]);
  try {
    await launch();
    await assert.rejects(fs.access(path.join(reviewRoot, ".review/state.json")));
    await app.evaluate(({ dialog }, directory) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] });
    }, reviewRoot);
    await click("choose");
    await page.waitForFunction(() => document.querySelector(".code-root p")?.textContent.includes("review workspace"));
    await click("start");
    await page.locator('[data-action="code-pause"]').waitFor();
    await click("next");
    await page.waitForFunction(() => document.querySelector(".patch-toolbar")?.textContent.includes("Hunk 2 of 4"));
    assert.equal((await read()).hunk, 1);
    await click("previous");
    await page.waitForFunction(() => document.querySelector(".patch-toolbar")?.textContent.includes("Hunk 1 of 4"));
    await click("next");
    await page.waitForFunction(() => document.querySelector(".patch-toolbar")?.textContent.includes("Hunk 2 of 4"));
    await page.locator("#code-comment").fill("Preserve the edge case. <img src=x onerror=alert(1)>");
    await click("comment");
    await page.locator(".code-comments .feedback").waitFor();
    assert.match((await read()).comments[0].anchor, /es-as:.*@@ -47/);
    assert.equal(await page.locator("img").count(), 0);
    await page.locator("#code-comment").fill("Please clarify the first change.");
    await click("reject");
    await page.locator('[data-action="code-resolve"]').waitFor();
    assert.equal(await page.locator('[data-action="code-accept"]').isDisabled(), true);
    await page.locator("#chat-input").fill("What are we reviewing here?");
    await page.locator("#chat-input").press("Enter");
    await page.waitForFunction(() => document.querySelector(".chat-message.assistant:last-child p")?.textContent.includes("R01: Small change 1"));
    await page.screenshot({ path: path.join(artifacts, "09-hunk-conversation.png") });
    await section("diff");
    assert.equal(await page.locator(".diff-hunk").count(), 2);
    await section("copy");
    await page.locator('[data-review-copy="teams"]').fill("A revised message grounded in the review.");
    await cli("comment", "Agent: I have read the requested change.");
    await click("save");
    await page.waitForFunction(() => document.querySelector("#toast")?.textContent.includes("review changed"));
    assert.equal(await page.locator('[data-review-copy="teams"]').inputValue(), "A revised message grounded in the review.");
    await click("refresh");
    await click("save");
    await page.waitForFunction(() => document.querySelector("#toast")?.textContent.includes("edits saved"));
    assert.equal((await read()).round.teams, "A revised message grounded in the review.");
    await section("patch");
    const savedPatches = (await read()).patches;
    await page.locator("#code-repo").selectOption("es-hf");
    await page.locator("#code-patch").fill("This is not a patch\n");
    await click("save");
    await click("resolve");
    await click("accept");
    await click("confirm");
    await page.waitForFunction(() => document.querySelector("#toast")?.classList.contains("error"));
    for (const repo of Object.keys(plan.repositories))
      assert.equal(await git(path.join(reviewRoot, repo), ["rev-parse", "master"]), plan.repositories[repo].base);
    await page.locator("#code-patch").fill(savedPatches["es-hf"]);
    await click("save");
    await page.locator("#code-repo").selectOption("es-as");
    await page.locator("#code-patch").fill(savedPatches["es-as"].replace("+first change", "+revised first change"));
    await click("save");
    await section("hunk");
    await cli("comment", "Agent: patch and handoff are revised; inspect before accepting.");
    await page.waitForFunction(() => document.querySelector(".code-comments")?.textContent.includes("Agent: patch and handoff are revised"));
    await click("next");
    await click("pause");
    await page.locator('[data-action="code-start"]').waitFor();
    await app.close(); app = null;
    delete env.YHWH_REVIEW_ROOT;
    await launch();
    assert.equal((await read()).root, reviewRoot);
    assert.equal((await read()).hunk, 1);
    assert.equal((await read()).active, false);
    await click("start");
    await click("accept");
    await page.screenshot({ path: path.join(artifacts, "10-paired-acceptance.png") });
    await click("confirm");
    await page.waitForFunction(() => document.querySelector(".round-title h2")?.textContent.includes("R02"));
    const accepted = await read();
    assert.match(accepted.master, /A revised message grounded in the review/);
    assert.doesNotMatch(accepted.master, /Preserve the edge case/);
    assert.match(accepted.board, /- \[x\] \[R01\]/);
    assert.match(await git(path.join(reviewRoot, "es-as"), ["show", "master:value.txt"]), /revised first change/);
    await section("records");
    await click("copy-master");
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), accepted.master);
    const exportDirectory = path.join(temp, "exports");
    await fs.mkdir(exportDirectory);
    await app.evaluate(({ dialog }, directory) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] });
    }, exportDirectory);
    await page.locator('[data-action="export"]').click();
    await page.waitForFunction(() => document.querySelector("#toast")?.textContent.includes("Files exported"));
    const [exportName] = await fs.readdir(exportDirectory);
    assert.equal(await fs.readFile(path.join(exportDirectory, exportName, "MASTER.md"), "utf8"), accepted.master);
    assert.equal(await fs.readFile(path.join(exportDirectory, exportName, "Kanbun.md"), "utf8"), accepted.board);
    await page.screenshot({ path: path.join(artifacts, "11-review-handoff.png") });
    await page.setViewportSize({ width: 1100, height: 740 });
    await section("hunk");
    await page.screenshot({ path: path.join(artifacts, "12-review-compact.png") });
    await click("accept");
    await click("confirm");
    await page.getByText("Every prepared round is accepted locally.", { exact: false }).waitFor();
    assert.equal((await read()).round, null);
    assert.equal(await page.locator('[data-action="code-accept"]').count(), 0);
    assert.deepEqual(errors, []);
    console.log("✓ Shared CLI/desktop review: navigation, anchored comments, rejection, stale edits, revision, failed patch, agent feedback, pause/restart, paired acceptance, final handoff, compact layout and completion");
  } catch (error) {
    if (app && page) await page.screenshot({ path: path.join(artifacts, "review-failure.png") }).catch(() => {});
    throw error;
  } finally {
    if (app) await app.close();
    await fs.rm(temp, { recursive: true, force: true });
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
