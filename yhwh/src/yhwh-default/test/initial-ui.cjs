const { _electron:electron }=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
(async()=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'yhwh-initial-ui-'));
  for(const variant of ['default','three']) {
    const cwd=path.join(temp,variant),config=path.join(temp,variant+'-config');await fs.mkdir(cwd);await fs.mkdir(config);
    const env={...process.env,YHWH_CONFIG_HOME:config,YHWH_SYSTEM_CONFIG:path.join(temp,'system'),YHWH_DATA_DIR:path.join(temp,'profile-'+variant),YHWH_THREE_DATA_DIR:path.join(temp,'profile-three'),YHWH_NO_SHELL_RC:'1',YHWH_NODE:process.execPath,YHWH_SHELL:require('node:child_process').execFileSync('which',['bash'],{encoding:'utf8'}).trim()};delete env.ELECTRON_RUN_AS_NODE;
    const launcher = variant === 'default';
    await fs.writeFile(path.join(config, 'rc'), `/\n    default_directory='${launcher ? cwd : temp}'\n`);
    const app=await electron.launch({executablePath:require('../../../lib/electron.cjs')(),cwd,args:[path.resolve(__dirname,variant==='three'?'../../yhwh-three':'..'),'--disable-gpu',...(launcher ? ['--desktop-launch'] : [])],env,timeout:60000});
    try{
      const page=await app.firstWindow(),errors=[];page.on('pageerror',error=>errors.push(error.message));
      await page.waitForFunction(()=>window.YHWH?.initial);
      assert.equal(await page.evaluate(() => window.YHWH.active().cwd), cwd);
      const terminal = page.locator('#terminal-panel'), files = page.locator('#navigation-area');
      const expanded = () => page.locator('#workspace').getAttribute('data-expanded');
      await page.keyboard.press('Control+ArrowUp'); await terminal.waitFor();
      const height = (await terminal.boundingBox()).height;
      await page.keyboard.press('Control+Alt+Shift+ArrowUp');
      assert.equal((await terminal.boundingBox()).height, height + 24);
      await page.keyboard.press('Control+ArrowUp'); assert.equal(await expanded(), 'terminal');
      await page.keyboard.press('Control+ArrowDown'); assert.equal(await expanded(), '');
      await page.keyboard.press('Control+ArrowDown'); await terminal.waitFor({ state: 'hidden' });
      await files.locator('#location').focus();
      await page.keyboard.press('Control+ArrowLeft'); await files.waitFor({ state: 'hidden' });
      await page.keyboard.press('Control+ArrowRight'); await files.waitFor();
      await page.keyboard.press('Control+ArrowRight'); assert.equal(await expanded(), 'files');
      await page.keyboard.press('Control+ArrowLeft'); assert.equal(await expanded(), '');
      await page.evaluate(() => window.YHWH.run('settings'));
      await page.locator('[data-category=keys]').click();
      await page.locator('[name=key_files_grow]').fill('Ctrl+Alt+Shift+G');
      await page.locator('[name=panel_resize_pixels]').fill('41');
      await page.getByRole('button', { name: 'Save settings' }).click();
      await page.locator('#dialog').waitFor({ state: 'hidden' });
      const width = (await files.boundingBox()).width;
      await page.keyboard.press('Control+Alt+Shift+G'); assert.equal((await files.boundingBox()).width, width + 41);
      await page.locator('#initial-commands').click();await page.waitForSelector('#initial-dialog[open] .initial-shelf');
      assert.ok(await page.locator('.initial-tile').count()>=6);
      const dialog = page.locator('#initial-dialog'), square = dialog.locator('[data-cell="0"]');
      await dialog.getByRole('button', { name: 'Script', exact: true }).click();
      const pwdTile = await dialog.locator('.initial-tile').filter({ has: page.locator('b', { hasText: /^pwd$/ }) }).boundingBox();
      const drop = await square.boundingBox();
      await page.mouse.move(pwdTile.x + pwdTile.width / 2, pwdTile.y + pwdTile.height / 2);
      await page.mouse.down();
      await page.mouse.move(drop.x + drop.width / 2, drop.y + drop.height / 2, { steps: 10 });
      await page.mouse.up();
      const stdout = dialog.locator('.initial-grid-output');
      await stdout.getByText(cwd, { exact: true }).waitFor();
      await square.click();
      await dialog.getByRole('button', { name: 'Edit tile' }).click();
      await dialog.getByRole('textbox', { name: 'Tile command and options' }).fill("echo 'Edited tile'");
      await dialog.getByRole('button', { name: 'Apply' }).click();
      await stdout.getByText('Edited tile', { exact: true }).waitFor();
      await dialog.getByRole('button', { name: 'Remove' }).click();
      await stdout.getByText('Script output appears here.').waitFor();
      await page.locator('#initial-dialog [data-close]').click();
      await page.evaluate(() => window.YHWH.run('focus-terminal'));
      await page.locator('#terminal-panel [data-command="terminal-interface"]').click();
      await page.locator('#initial-dialog').getByRole('button', { name: 'Initial', exact: true }).click();
      await page.locator('#terminal-initial .initial-workbench').waitFor();
      assert.ok(await page.locator('#terminals').isHidden());
      await page.locator('#terminal-initial .initial-tile').filter({ has: page.locator('b', { hasText: /^pwd$/ }) }).click();
      await page.locator('#terminal-initial .initial-output', { hasText: cwd }).waitFor();
      await page.locator('#terminal-panel [data-command="terminal-interface"]').click();
      await page.locator('#initial-dialog [data-initial="terminal"]').click();
      await page.locator('#terminals').waitFor();
      await page.evaluate(()=>window.YHWH.initial.run("mkdir check; echo 'Abe' > check/note.md; ls check | view"));
      await page.waitForSelector('.document-content:not([hidden]) .initial-file-view');
      assert.match(await page.locator('.document-content:not([hidden]) .initial-file-grid').textContent(),/note.md/);
      assert.equal(await fs.readFile(path.join(cwd,'check/note.md'),'utf8'),'Abe');
      const tabs=await page.evaluate(()=>window.YHWH.tabs.length);
      await page.evaluate(()=>window.YHWH.initial.run('fm .'));
      assert.equal(await page.evaluate(()=>window.YHWH.tabs.length),tabs+1);
      await page.evaluate(()=>window.YHWH.initial.run('touch newly-created.txt'));
      await page.waitForFunction(()=>document.querySelector('.document-content:not([hidden]) .initial-file-grid')?.textContent.includes('newly-created.txt'));
      assert.deepEqual(errors,[]);console.log(`Passed ${variant}: Initial shelf, typed pipeline, versioned file write, snapshot and live file manager.`);
    }finally{await app.close();}
  }
  await fs.rm(temp,{recursive:true,force:true});
})().catch(error=>{console.error(error);process.exitCode=1;});
